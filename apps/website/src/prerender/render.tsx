import { RouterProvider } from "@tanstack/react-router";
import { renderToString } from "react-dom/server";
import type { DocumentAssets } from "../components/Document";
import { createSiteRouter } from "../router";
import {
  HTML_LANG,
  LOCALES,
  type Locale,
  REDIRECTS,
  ROUTES,
  type Redirect,
  absoluteUrl,
  localePrefix,
  pagePath,
} from "../site";

/** The full HTML of the page at `path`, or of the 404 page in the path's locale when no page matches. */
export const renderPath = async (path: string, assets: DocumentAssets): Promise<string> => {
  const router = createSiteRouter(path, assets);
  await router.load();
  return `<!doctype html>${renderToString(<RouterProvider router={router} />)}`;
};

/** A path no page matches, under `locale`'s prefix, to render that locale's 404 page. */
export const notFoundProbePath = (locale: Locale): string => `${localePrefix(locale)}__not-found__/`;

const escapeXml = (value: string): string =>
  value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Every page in every locale, each with its hreflang alternates (the same set the pages' <head> lists). No <lastmod>: every release rebuilds the site, so the build date would claim a change on every page each time, and search engines ignore a lastmod that is not accurate. */
export const buildSitemap = (): string => {
  const urls = ROUTES.map((route) => {
    const alternates = [
      ...LOCALES.map((alt) => ({ lang: HTML_LANG[alt], href: absoluteUrl(pagePath(alt, route.page)) })),
      { lang: "x-default", href: absoluteUrl(pagePath("en", route.page)) },
    ]
      .map((alt) => `    <xhtml:link rel="alternate" hreflang="${alt.lang}" href="${escapeXml(alt.href)}"/>`)
      .join("\n");
    return `  <url>\n    <loc>${escapeXml(absoluteUrl(route.path))}</loc>\n${alternates}\n  </url>`;
  });
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls.join("\n")}\n</urlset>\n`;
};

// The app, its API and shared result pages are not for search engines. Survey pages (/s/*) are left to the server, which owns their noindex.
export const ROBOTS_TXT = `User-agent: *
Allow: /
Disallow: /app/
Disallow: /api/
Disallow: /share/
Sitemap: ${absoluteUrl("/sitemap.xml")}
`;

/** nginx `location` blocks for the inbound redirects, included by the image's server block (apps/website/nginx/default.conf). */
export const buildRedirectsConf = (redirects: Redirect[] = REDIRECTS): string =>
  [
    "# Generated by apps/website/src/prerender (REDIRECTS in src/site.ts). Do not edit.",
    ...redirects.flatMap((redirect) =>
      [redirect.from, `${redirect.from}/`].map(
        (from) => `location = ${from} { return ${redirect.status} "${redirect.to}"; }`
      )
    ),
    "",
  ].join("\n");
