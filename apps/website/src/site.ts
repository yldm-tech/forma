/** Whether `path` falls under a reserved prefix: the prefix itself, or anything below it. */
export const isReservedPath = (path: string): boolean =>
  RESERVED_PREFIXES.some((prefix) => path === prefix || path.startsWith(`${prefix}/`));

/** Where every built asset lives (hashed JS and CSS under assets/, icons, OG images), so the site claims one prefix rather than many. */
