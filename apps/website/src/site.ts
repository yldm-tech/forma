// The site's fixed facts: where it lives, which locales and pages it has, which paths it may never claim, and what the build-time switches are. Everything that emits a URL reads it from here.

export const SITE_ORIGIN = "https://forma.yldm.ai";
export const GITHUB_URL = "https://github.com/yldm-tech/forma";
export const SECURITY_POLICY_URL = `${GITHUB_URL}/blob/main/SECURITY.md`;
export const SECURITY_EMAIL = "security@yldm.ai";
export const MCP_URL = `${SITE_ORIGIN}/api/mcp`;

// Whether forma.yldm.ai accepts public sign-ups. The server only opens sign-up with IS_FORMA_CLOUD=1, which production does not set, so the default sends visitors to self-hosting instead of a sign-up page that would 404. Set by the build's SIGNUP_OPEN=1 (vite.config.ts).
export const SIGNUP_OPEN: boolean = __SIGNUP_OPEN__;

export const LOCALES = ["en", "zh", "ja"] as const;
export type Locale = (typeof LOCALES)[number];

/** `<html lang>` and hreflang value per locale. */
export const HTML_LANG: Record<Locale, string> = { en: "en", zh: "zh-Hans", ja: "ja" };
export const OG_LOCALE: Record<Locale, string> = { en: "en_US", zh: "zh_CN", ja: "ja_JP" };
/** Each locale's name in its own language, as the language switcher shows it. */
export const LOCALE_NAME: Record<Locale, string> = { en: "English", zh: "简体中文", ja: "日本語" };

export const PAGES = [
  "home",
  "formBuilder",
  "websiteSurvey",
  "inAppSurvey",
  "integrations",
  "developers",
  "selfHosting",
  "security",
] as const;
export type PageId = (typeof PAGES)[number];

/** Path of each page below its locale prefix, with the trailing slash every URL on the site carries. */
export const PAGE_SLUG: Record<PageId, string> = {
  home: "",
  formBuilder: "form-builder/",
  websiteSurvey: "website-survey/",
  inAppSurvey: "in-app-survey/",
  integrations: "integrations/",
  developers: "developers/",
  selfHosting: "self-hosting/",
  security: "security/",
};

export const localePrefix = (locale: Locale): string => (locale === "en" ? "/" : `/${locale}/`);

export const pagePath = (locale: Locale, page: PageId): string => `${localePrefix(locale)}${PAGE_SLUG[page]}`;

export const notFoundPath = (locale: Locale): string => `${localePrefix(locale)}404.html`;

export const absoluteUrl = (path: string): string => `${SITE_ORIGIN}${path}`;

/** The 1200 × 630 share image of a page (public/_site/og, generated by scripts/og-images.ts). */
export const ogImagePath = (locale: Locale, page: PageId): string => `/_site/og/${locale}/${page}.png`;

export interface SiteRoute {
  path: string;
  locale: Locale;
  page: PageId;
}

/** Every page the build emits, in every locale. */
export const ROUTES: SiteRoute[] = LOCALES.flatMap((locale) =>
  PAGES.map((page) => ({ path: pagePath(locale, page), locale, page }))
);

/** The locale a path belongs to, by its prefix. Used for pages the router does not know (the 404 page). */
export const localeOfPath = (path: string): Locale =>
  LOCALES.find((locale) => locale !== "en" && (path === `/${locale}` || path.startsWith(`/${locale}/`))) ??
  "en";

// Paths the website must never serve on forma.yldm.ai: the app (/app), the Go server's public pages, APIs, SDK bundles and well-known endpoints, the documentation, and the files the server serves from apps/web/public that stored surveys, emails and customer sites load cross-origin. The ingress sends these to the server or the docs image, so a page here would be unreachable at best and would shadow a live URL at worst.
